// Plain-markdown export so a guide can be pasted into Slack, Notion, a ticket or a PR.
import { ACTOR, EVIDENCE, TIER, formatDuration } from "./format";
import type { Guide } from "./types";

export function guideToMarkdown(g: Guide, pageUrl?: string): string {
  const cite = (ids: string[]) => (ids.length ? ` [${ids.join(", ")}]` : "");
  const lines: string[] = [];
  lines.push(`# ${g.app.name}: OAuth app setup`);
  lines.push("");
  lines.push(`**${TIER[g.verdict.tier].label}.** ${g.verdict.summary}`);
  lines.push("");
  lines.push(`- **First working connection:** ${formatDuration(g.clocks.firstConnection.effort)} of work, ${formatDuration(g.clocks.firstConnection.wait)} waiting. ${g.clocks.firstConnection.definition}`);
  lines.push(`- **Production:** ${formatDuration(g.clocks.production.effort)} of work, ${formatDuration(g.clocks.production.wait)} waiting. ${g.clocks.production.definition}`);
  lines.push(`- **Cost:** ${g.verdict.cost.summary}`);
  lines.push(`- **Each customer's admin must act:** ${g.verdict.customerAdminRequired ? "Yes" : "No"}`);
  lines.push("");
  for (const stage of g.stages) {
    lines.push(`## ${stage.name}`);
    lines.push(`_Unlocks: ${stage.unlocks}_`);
    lines.push("");
    stage.steps.forEach((s, i) => {
      lines.push(`${i + 1}. **${s.title}** (${ACTOR[s.actor]})${cite(s.claimIds)}`);
      lines.push(`   ${s.instructions}`);
      if (s.agentHelp) lines.push(`   - Agent help: ${s.agentHelp}`);
      if (s.whyHuman) lines.push(`   - Why a human: ${s.whyHuman}`);
    });
    lines.push("");
  }
  if (g.gotchas.length) {
    lines.push("## Gotchas");
    for (const x of g.gotchas) lines.push(`- **${x.symptom}** ${x.cause} Fix: ${x.fix}${cite(x.claimIds)}`);
    lines.push("");
  }
  lines.push("## Composio setup");
  lines.push(`- Redirect URI: \`${g.composioSetup.redirectUri}\``);
  lines.push(`- Default scopes: ${g.composioSetup.defaultScopes.length ? g.composioSetup.defaultScopes.map((s) => `\`${s}\``).join(", ") : "none (set on the provider app)"}`);
  for (const n of g.composioSetup.scopeNotes) lines.push(`- \`${n.scope}\` (${n.sensitivity}): ${n.note}`);
  lines.push("");
  lines.push("## Evidence");
  for (const c of g.claims) {
    const src = c.evidence.sources.map((s) => s.url).join(", ");
    lines.push(`- **[${c.id}]** ${c.text} _${EVIDENCE[c.evidence.level].label}${src ? `: ${src}` : ""}_`);
  }
  if (g.openQuestions.length) {
    lines.push("");
    lines.push("## Still open");
    for (const q of g.openQuestions) lines.push(`- ${q.question} (${q.whyItMatters})`);
  }
  lines.push("");
  lines.push(`_${g.meta.generatedBy === "live_agent" ? "Generated by the research agent" : "Curated guide"}, ${g.meta.generatedAt.slice(0, 10)}.${pageUrl ? ` ${pageUrl}` : ""}_`);
  return lines.join("\n");
}
